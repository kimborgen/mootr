#!/usr/bin/env node
// Regenerates everything derived from api/openapi.yaml (S-2388, S-2194 plan section 3):
//   api/openapi.bundled.yaml   the spec with its relative $refs inlined into components
//   web/src/api/types.gen.ts   openapi-typescript (pinned in web/package.json)
// and with `--go`, on storage only, instead of those two:
//   go/internal/api/api.gen.go oapi-codegen (pinned below, run with `go run`), from the bundle
// `--check` regenerates into a scratch folder and fails when a committed file differs.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';
import { isMain } from './main-guard.mjs';

export const OAPI_CODEGEN = 'github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.5.1';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GO = process.env.GO ?? (existsSync(join(process.env.HOME ?? '', '.local/go/bin/go')) ? join(process.env.HOME, '.local/go/bin/go') : 'go');
const BANNER = '# Generated by scripts/api-gen.mjs from api/openapi.yaml; do not edit.\n';

// Inlines relative file $refs. A path item file is copied in place; a schema file under a
// `schemas/` folder becomes components.schemas.NAME (NAME is the file's name), and a ref to it
// becomes `#/components/schemas/NAME`. `#/...` refs inside a file stay as they are: they point at
// the root's components, which is where every shared piece lives.
export function bundle(rootFile) {
  const doc = parse(readFileSync(rootFile, 'utf8'));
  const schemas = (doc.components.schemas ??= {});
  const walk = (node, file) => {
    if (Array.isArray(node)) return node.map((n) => walk(n, file));
    if (!node || typeof node !== 'object') return node;
    if (typeof node.$ref === 'string' && !node.$ref.startsWith('#')) {
      const target = resolve(dirname(file), node.$ref);
      const rel = relative(dirname(rootFile), target);
      const m = /^schemas\/([A-Za-z0-9]+)\.yaml$/.exec(rel);
      const loaded = m && schemas[m[1]] ? null : walk(parse(readFileSync(target, 'utf8')), target);
      if (m) {
        schemas[m[1]] ??= loaded;
        return { $ref: `#/components/schemas/${m[1]}` };
      }
      return loaded;
    }
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, walk(v, file)]));
  };
  // The root's own component schemas that are file refs are inlined under their name; every other
  // ref to such a file then resolves to `#/components/schemas/NAME` (never to itself).
  const named = { ...schemas };
  for (const [name, def] of Object.entries(named)) {
    if (typeof def.$ref !== 'string' || def.$ref.startsWith('#')) continue;
    const file = resolve(dirname(rootFile), def.$ref);
    if (relative(dirname(rootFile), file) !== `schemas/${name}.yaml`) throw new Error(`schema ${name} must come from schemas/${name}.yaml`);
    schemas[name] = walk(parse(readFileSync(file, 'utf8')), file);
  }
  return walk(doc, rootFile);
}

// The bundle and the TypeScript types: pure Node, run anywhere (the `api-gen` test checks them on every machine).
function generate(outRoot) {
  const spec = join(outRoot, 'api/openapi.bundled.yaml');
  mkdirSync(dirname(spec), { recursive: true });
  writeFileSync(spec, BANNER + stringify(bundle(join(ROOT, 'api/openapi.yaml')), { lineWidth: 0 }));
  const ts = join(outRoot, 'web/src/api/types.gen.ts');
  mkdirSync(dirname(ts), { recursive: true });
  execFileSync('node', [join(ROOT, 'web/node_modules/openapi-typescript/bin/cli.js'), spec, '-o', ts], { stdio: 'inherit' });
  return ['api/openapi.bundled.yaml', 'web/src/api/types.gen.ts'];
}

// The Go types and server interface: needs Go, so storage only (Go never builds on the gate machine). A generator
// error throws; go/api-check.sh runs `--go --check` in the `go` gate.
function generateGo(outRoot) {
  const spec = join(ROOT, 'api/openapi.bundled.yaml');
  const goDir = join(outRoot, 'go');
  mkdirSync(join(goDir, 'internal/api'), { recursive: true });
  // The generator reads go/go.mod for the Go version, so a scratch copy needs one too.
  if (goDir !== join(ROOT, 'go') && existsSync(join(ROOT, 'go/go.mod'))) copyFileSync(join(ROOT, 'go/go.mod'), join(goDir, 'go.mod'));
  execFileSync(GO, ['run', OAPI_CODEGEN, '-config', join(ROOT, 'api/oapi-codegen.yaml'), spec], { cwd: goDir, stdio: 'inherit' });
  return ['go/internal/api/api.gen.go'];
}

const sameAsCommitted = (tmp, files) => files.filter((f) => !existsSync(join(ROOT, f)) || readFileSync(join(ROOT, f), 'utf8') !== readFileSync(join(tmp, f), 'utf8'));

if (isMain(import.meta.url)) {
  const go = process.argv.includes('--go');
  if (process.argv.includes('--check')) {
    const tmp = mkdtempSync(join(tmpdir(), 'api-gen.'));
    try {
      const files = go ? generateGo(tmp) : generate(tmp);
      const stale = sameAsCommitted(tmp, files);
      if (stale.length) {
        console.error(`api-gen: stale generated files: ${stale.join(', ')}\nrun: node scripts/api-gen.mjs${go ? ' --go' : ''}`);
        process.exit(1);
      }
      console.log(`api-gen: ${files.length} generated files are current`);
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
  } else {
    console.log(`api-gen: wrote ${(go ? generateGo(ROOT) : generate(ROOT)).join(', ')}`);
  }
}
